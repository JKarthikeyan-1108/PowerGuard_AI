'use client';

import React from 'react';
import { Badge } from '@/components/ui/badge';
import { Cpu, Radio, Sparkles } from 'lucide-react';
import { cn } from '@/lib/utils';

interface DataSourceBadgeProps {
  isSimulated?: boolean;
  dataSource?: string;
  className?: string;
  size?: 'sm' | 'md';
}

export const DataSourceBadge: React.FC<DataSourceBadgeProps> = ({
  isSimulated,
  dataSource,
  className,
  size = 'sm',
}) => {
  const isDemo = isSimulated || (dataSource && dataSource.toUpperCase().includes('SIMULATOR'));

  if (isDemo) {
    return (
      <span
        title="Simulated sensor reading generated by testing algorithm — distinct from physical meter hardware."
        className={cn(
          'inline-flex items-center gap-1 font-medium rounded-full border border-amber-200 dark:border-amber-800/60 bg-amber-50 dark:bg-amber-950/40 text-amber-700 dark:text-amber-400',
          size === 'sm' ? 'px-2 py-0.5 text-[10px]' : 'px-2.5 py-1 text-xs',
          className
        )}
      >
        <Sparkles className={size === 'sm' ? 'h-2.5 w-2.5' : 'h-3 w-3'} />
        <span>Demo / Simulated</span>
      </span>
    );
  }

  return (
    <span
      title="Verified physical telemetry transmitted by ESP32 microcontroller with PZEM-004T energy meter."
      className={cn(
        'inline-flex items-center gap-1 font-medium rounded-full border border-emerald-200 dark:border-emerald-800/60 bg-emerald-50 dark:bg-emerald-950/40 text-emerald-700 dark:text-emerald-400',
        size === 'sm' ? 'px-2 py-0.5 text-[10px]' : 'px-2.5 py-1 text-xs',
        className
      )}
    >
      <Radio className={cn('animate-pulse text-emerald-500', size === 'sm' ? 'h-2.5 w-2.5' : 'h-3 w-3')} />
      <span>ESP32 Hardware</span>
    </span>
  );
};
